"""Post-training int8 quantization + bit-exact integer reference + C export.

Scheme (identical in firmware/edge_ml/model.c):
  z    = (x - mu) * inv_sd                         float32, per feature
  zq   = clamp(floor(z * inv_s_in + 0.5), -127, 127) int8
  acc1 = W1q @ zq + b1q                            int32   (W1q per-tensor int8)
  h    = clamp(rq(acc1, M1, S1), 0, 127)           int8    (ReLU folded into clamp)
  acc2 = W2q @ h + b2q                             int32
  y    = argmax(acc2)                              (first max on ties)
  rq(a, M, S) = (a * M + 2^(S-1)) >> S              int64, M in [2^30, 2^31)
Logistic regression is the same without the hidden layer.
Calibration ranges use the 99.9th percentile of |activation| on training
windows (fixed a priori), so rare outliers saturate instead of wasting range.
"""
import json
import math

import numpy as np

import data
import experiments as ex

PCT = 99.9


def _scale(v):
    return max(float(np.percentile(np.abs(v), PCT)), 1e-12) / 127.0


def _quant_w(W):
    s = float(np.abs(W).max()) / 127.0
    return np.clip(np.round(W / s), -127, 127).astype(np.int8), s


def _fixed_point(m):
    """m = M * 2^-S with M in [2^30, 2^31)."""
    frac, exp = math.frexp(m)                 # m = frac * 2^exp, frac in [0.5,1)
    M = int(round(frac * (1 << 31)))
    S = 31 - exp
    if M == (1 << 31):
        M //= 2
        S -= 1
    assert 0 < S < 63
    return M, S


class QModel:
    """Integer model from a fitted sklearn pipeline (StandardScaler + LR/MLP)."""

    def __init__(self, pipe, Xcal):
        sc, clf = pipe[0], pipe[-1]
        self.kind = "mlp" if hasattr(clf, "coefs_") else "logreg"
        self.mu = sc.mean_.astype(np.float32)
        self.inv_sd = (1.0 / sc.scale_).astype(np.float32)
        z = self._z(Xcal)
        self.s_in = _scale(z)
        self.inv_s_in = np.float32(1.0 / self.s_in)
        if self.kind == "logreg":
            W, b = clf.coef_, clf.intercept_
            self.W1, self.s_w1 = _quant_w(W)
            self.b1 = np.round(b / (self.s_in * self.s_w1)).astype(np.int32)
        else:
            W1, b1 = clf.coefs_[0].T, clf.intercepts_[0]
            W2, b2 = clf.coefs_[1].T, clf.intercepts_[1]
            self.W1, self.s_w1 = _quant_w(W1)
            self.b1 = np.round(b1 / (self.s_in * self.s_w1)).astype(np.int32)
            h = np.maximum(z.astype(np.float64) @ W1.T + b1, 0)
            self.s_h = _scale(h[h > 0]) if (h > 0).any() else 1.0
            self.M1, self.S1 = _fixed_point(self.s_in * self.s_w1 / self.s_h)
            self.W2, self.s_w2 = _quant_w(W2)
            self.b2 = np.round(b2 / (self.s_h * self.s_w2)).astype(np.int32)

    def _z(self, X):
        return (X.astype(np.float32) - self.mu) * self.inv_sd

    def quant_input(self, X):
        zq = np.floor(self._z(X) * self.inv_s_in + np.float32(0.5))
        return np.clip(zq, -127, 127).astype(np.int8)

    def logits_from_q(self, zq):
        acc = zq.astype(np.int64) @ self.W1.T.astype(np.int64) + self.b1
        if self.kind == "logreg":
            return acc
        h = (acc * self.M1 + (1 << (self.S1 - 1))) >> self.S1
        h = np.clip(h, 0, 127)
        return h @ self.W2.T.astype(np.int64) + self.b2

    def predict(self, X):
        return np.argmax(self.logits_from_q(self.quant_input(X)), axis=1)

    # ---------- C export ----------
    def to_c_header(self, name, fs, nfft, meta):
        def arr(ctype, nm, a):
            flat = ", ".join(str(int(v)) if np.issubdtype(np.asarray(a).dtype, np.integer)
                             else f"{float(v):.9g}f" for v in np.ravel(a))
            return f"static const {ctype} {nm}[{np.size(a)}] = {{{flat}}};\n"
        n_in, n_out = self.W1.shape[1], (self.W1 if self.kind == "logreg" else self.W2).shape[0]
        g = f"EDGE_ML_MODEL_{name.upper()}_H"
        s = [f"/* Auto-generated by src/quantize.py. Do not edit.\n"]
        s += [f"   {k}: {v}\n" for k, v in meta.items()]
        s += [f"*/\n#ifndef {g}\n#define {g}\n#include <stdint.h>\n\n",
              f"#define EM_FS {fs}\n#define EM_WINDOW {fs}\n#define EM_NFFT {nfft}\n",
              f"#define EM_N_FEATURES {n_in}\n#define EM_N_CLASSES {n_out}\n",
              f"#define EM_HAS_HIDDEN {int(self.kind == 'mlp')}\n"]
        if self.kind == "mlp":
            s += [f"#define EM_N_HIDDEN {self.W1.shape[0]}\n",
                  f"#define EM_M1 {self.M1}LL\n#define EM_S1 {self.S1}\n"]
        s += [f"static const float em_inv_s_in = {float(self.inv_s_in):.9g}f;\n",
              arr("float", "em_mu", self.mu), arr("float", "em_inv_sd", self.inv_sd),
              arr("int8_t", "em_W1", self.W1), arr("int32_t", "em_b1", self.b1)]
        if self.kind == "mlp":
            s += [arr("int8_t", "em_W2", self.W2), arr("int32_t", "em_b2", self.b2)]
        s += ["#endif\n"]
        return "".join(s)


def evaluate(fs):
    """LOLO: float vs int8 accuracy for both models; returns per-fold artefacts."""
    ex.CFG["fs"] = fs
    recs = data.load_all(fs)
    rng = np.random.default_rng(ex.SEED)
    out = {m: {"y": [], "float": [], "int8": []} for m in ("logreg", "mlp")}
    fitted = {}
    for name, tr, te in ex.folds(recs, "lolo"):
        Xtr, ytr, _ = ex.featurize(tr, ex.TRAIN)
        Xte, yte, _ = ex.featurize(te, ex.TEST)
        Xb, yb = ex.balance(Xtr, ytr, rng)
        for m, pipe in ex.make_models().items():
            pipe.fit(Xb, yb)
            q = QModel(pipe, Xtr)
            out[m]["y"].append(yte)
            out[m]["float"].append(pipe.predict(Xte))
            out[m]["int8"].append(q.predict(Xte))
            fitted[(name, m)] = (pipe, q, te)
    summary = {}
    for m, d in out.items():
        y, pf, pq = (np.concatenate(d[k]) for k in ("y", "float", "int8"))
        summary[m] = {
            "float_acc": float((pf == y).mean()), "int8_acc": float((pq == y).mean()),
            "float_int8_agreement": float((pf == pq).mean()),
            "int8_far": float((pq[y == 0] != 0).mean()),
            "int8_tpr": float((pq[y != 0] != 0).mean()),
            "n": int(len(y)),
        }
    ex.CFG["fs"] = data.FS_TARGET
    return summary, fitted


if __name__ == "__main__":
    res = {}
    for fs in (1666, 6664):
        s, _ = evaluate(fs)
        res[fs] = s
        for m, v in s.items():
            print(f"fs={fs} {m:<7} float={v['float_acc']:.3f} int8={v['int8_acc']:.3f} "
                  f"agree={v['float_int8_agreement']:.3f} int8 TPR={v['int8_tpr']:.3f} "
                  f"FAR={v['int8_far']:.3f}", flush=True)
    (data.ROOT / "results").mkdir(exist_ok=True)
    (data.ROOT / "results" / "quantization.json").write_text(json.dumps(res, indent=1))
